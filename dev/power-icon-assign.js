/**
 * Insurrection: paraphysics power icon assign (GM).
 *
 * Sets the icon of every paraphysics power from the power icon set (the 18 Tier 1 powers: three
 * each of Astrokinesis, Telekinesis, Telepathy, Pyrokinesis, Vitakinesis and Optics, each on a ring
 * in its discipline's color with a corner sigil). It changes both the power items in the world and
 * the copies characters already carry, so a sheet shows the new icon straight away.
 *
 * It matches BY NAME AND DISCIPLINE (system.paraphysics.discipline), never by name alone, because a
 * role ability can share a power's name. Names match loosely (case and punctuation ignored). As in
 * the powers macro, a power with no discipline set counts as Astrokinesis, because the first build
 * left Gravbolt blank in some worlds. Generated by docs/foundry-icons/make_power_assign.py.
 *
 *   1. Upload every file in docs/foundry-icons/dist-powers/ into ONE folder through Foundry's file
 *      picker (create the folder, then drag all the files in at once). CFG.folder is the folder
 *      Johnald approved, home/Insurrection/Icons/Power Icons.
 *   2. Run as GM with mode "dry". Nothing changes; a window reports what would.
 *   3. Set mode to "apply" and run again.
 *   4. Mode "revert" puts back each icon the item had before (kept in the world flag
 *      flags.world.iropIconPrev on the item).
 *
 * In a NEW world, run the Tier 1 powers macro first (it makes the items with Foundry's core
 * placeholder pictures), then this one. The powers macro only replaces a picture that is blank, the
 * mystery man or the item bag, so running it again after this keeps the new icons.
 *
 * Hosts differ: Sqyre stores paths with a "media/" prefix and a plain browse of the folder once
 * failed. So this tries every file source the server offers against several forms of the folder
 * path, takes the first listing that holds the icons, and sets each icon to the exact path that
 * listing reports.
 */
(async () => {

  /* ---- config ---------------------------------------------------------- */
  const CFG = {
    mode: "dry",                                    // "dry" | "apply" | "revert"
    folder: "home/Insurrection/Icons/Power Icons",  // the uploaded folder, no trailing slash
    source: "data",                                 // file source tried first when checking the files exist
    verifyFiles: true,                              // set false only if the check fails on your host
    itemType: "ability",                            // the system's ability item type
    flag: "iropIconPrev",                           // world flag holding the previous icon
    chunk: 50                                       // documents per update call
  };

  /* ---- power name, discipline, icon file ------------------------------- */
  const ICONS = [
    ["Gravbolt", "astrokinesis", "power-astrokinesis-gravbolt.webp"],
    ["Gravitic Rip", "astrokinesis", "power-astrokinesis-gravitic-rip.webp"],
    ["Penumbra", "astrokinesis", "power-astrokinesis-penumbra.webp"],
    ["Kinetic Dart", "telekinesis", "power-telekinesis-kinetic-dart.webp"],
    ["Throw", "telekinesis", "power-telekinesis-throw.webp"],
    ["Kinetic Brace", "telekinesis", "power-telekinesis-kinetic-brace.webp"],
    ["Psychic Spike", "telepathy", "power-telepathy-psychic-spike.webp"],
    ["Forewarn", "telepathy", "power-telepathy-forewarn.webp"],
    ["Unease", "telepathy", "power-telepathy-unease.webp"],
    ["Flare", "pyrokinesis", "power-pyrokinesis-flare.webp"],
    ["Kindle", "pyrokinesis", "power-pyrokinesis-kindle.webp"],
    ["Ember Ward", "pyrokinesis", "power-pyrokinesis-ember-ward.webp"],
    ["Mend", "vitakinesis", "power-vitakinesis-mend.webp"],
    ["Vigor", "vitakinesis", "power-vitakinesis-vigor.webp"],
    ["Crystalline Skin", "vitakinesis", "power-vitakinesis-crystalline-skin.webp"],
    ["Dazzle", "optics", "power-optics-dazzle.webp"],
    ["Blur", "optics", "power-optics-blur.webp"],
    ["Reveal", "optics", "power-optics-reveal.webp"]
  ];

  const tag = "%c[power icons]", style = "color:#4fd6ef;font-weight:bold";
  const log = (...m) => console.log(tag, style, ...m);
  const esc = s => String(s ?? "").replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
  const fold = s => String(s ?? "").normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[^a-z0-9]/g, "");
  if (!game.user?.isGM) return ui.notifications.error("Power icons: run this as a GM.");
  const folder = String(CFG.folder).replace(/\/+$/, "");
  const notes = [];

  /* ---- the powers: world items, and the copies on actors ---------------- */
  const byKey = new Map(ICONS.map(([name, discipline, file]) => [`${discipline}|${fold(name)}`, { name, discipline, file, path: `${folder}/${file}` }]));
  const disciplines = new Set(ICONS.map(([, d]) => d));
  const discOf = it => String(it.system?.paraphysics?.discipline ?? "").toLowerCase();
  // The icon for an item, or null. A blank discipline counts as Astrokinesis.
  const known = it => byKey.get(`${discOf(it)}|${fold(it.name)}`) ?? (discOf(it) === "" ? byKey.get(`astrokinesis|${fold(it.name)}`) : null) ?? null;
  const worldItems = game.items.filter(i => i.type === CFG.itemType && known(i));
  const carried = [];
  for (const actor of game.actors) for (const item of actor.items) if (item.type === CFG.itemType && known(item)) carried.push({ actor, item });

  // Powers (by discipline) in this world that have no icon yet, such as a Tier 2 power not drawn.
  // Role abilities have no discipline and are never listed.
  const isPowerLike = it => it.type === CFG.itemType && disciplines.has(discOf(it));
  // (Foundry's Collection has no flatMap, so gather every item with plain loops.)
  const everyItem = [...game.items];
  for (const actor of game.actors) for (const item of actor.items) everyItem.push(item);
  const noIcon = [...new Set(everyItem.filter(it => isPowerLike(it) && !known(it)).map(it => `${it.name} (${discOf(it)})`))];
  const seen = new Set([...worldItems, ...carried.map(c => c.item)].map(it => { const e = known(it); return `${e.discipline}|${fold(e.name)}`; }));
  const noItem = ICONS.filter(([name, d]) => !seen.has(`${d}|${fold(name)}`)).map(([name, d]) => `${name} (${d})`);

  /* ---- revert ------------------------------------------------------------ */
  if (CFG.mode === "revert") {
    const back = it => ({ _id: it.id, img: it.getFlag("world", CFG.flag), [`flags.world.-=${CFG.flag}`]: null });
    const w = game.items.filter(i => i.type === CFG.itemType && i.getFlag("world", CFG.flag) !== undefined).map(back);
    for (let i = 0; i < w.length; i += CFG.chunk) await Item.updateDocuments(w.slice(i, i + CFG.chunk));
    let n = 0;
    for (const actor of game.actors) {
      const ups = actor.items.filter(i => i.type === CFG.itemType && i.getFlag("world", CFG.flag) !== undefined).map(back);
      if (ups.length) { await actor.updateEmbeddedDocuments("Item", ups); n += ups.length; }
    }
    ui.notifications.info(`Power icons: reverted ${w.length} world item(s) and ${n} carried cop${n === 1 ? "y" : "ies"}.`);
    return log("reverted", w.length, n);
  }

  /* ---- find the uploaded files -------------------------------------------- */
  let missing = new Set(), found = null;
  if (CFG.verifyFiles) {
    const FP = foundry?.applications?.apps?.FilePicker?.implementation ?? globalThis.FilePicker;
    const sources = new Set([CFG.source]);
    for (const s of (game.data?.files?.storages ?? [])) sources.add(s);
    try { for (const s of Object.keys(new FP().sources ?? {})) sources.add(s); } catch (e) { /* no instance sources */ }
    for (const s of ["sqyre", "public", "s3", "forgevtt"]) sources.add(s);
    const bare = folder.replace(/^media\//, "");
    const targets = [...new Set([folder, bare, `media/${bare}`, bare.replace(/^home\//, ""), encodeURI(folder)])];
    const wanted = new Set(ICONS.map(([, , file]) => file));
    const tried = [];
    search: for (const src of sources) for (const tgt of targets) {
      try {
        const files = (await FP.browse(src, tgt))?.files ?? [];
        const ours = files.filter(f => wanted.has(decodeURIComponent(String(f).split("/").pop())));
        if (!ours.length) { tried.push(`${src} : ${tgt} (${files.length} files, none of ours)`); continue; }
        found = { src, tgt, paths: new Map(ours.map(f => [decodeURIComponent(String(f).split("/").pop()), String(f)])) };
        break search;
      } catch (e) { tried.push(`${src} : ${tgt} (${e?.message ?? e})`); }
    }
    if (found) {
      for (const entry of byKey.values()) if (found.paths.has(entry.file)) entry.path = found.paths.get(entry.file);
      missing = new Set([...wanted].filter(f => !found.paths.has(f)));
      notes.push(`Found the icons on file source "${found.src}" at "${found.tgt}". Each icon is set to the path that listing reports, for example "${found.paths.values().next().value}".`);
      if (missing.size) notes.push(`${missing.size} icon file(s) were not in that folder and will be skipped: ${[...missing].slice(0, 8).join(", ")}${missing.size > 8 ? " ..." : ""}`);
    } else {
      log("tried", tried);
      notes.push(`Could not find the uploaded icons on any file source. Tried ${tried.length} combinations (listed in the console). Sources the server reports: ${(game.data?.files?.storages ?? []).join(", ") || "none"}. Send Claude the path the file picker shows for one uploaded icon.`);
      if (CFG.mode === "apply") {
        log("file check failed, nothing changed", notes);
        return ui.notifications.error("Power icons: could not find the uploaded icons, nothing changed. See the console.");
      }
    }
  }

  /* ---- what would change -------------------------------------------------- */
  const want = it => { const e = known(it); return e && !missing.has(e.file) ? e.path : null; };
  const worldChanges = worldItems.filter(it => want(it) && it.img !== want(it));
  const carriedChanges = carried.filter(({ item }) => want(item) && item.img !== want(item));
  const sameCount = worldItems.length + carried.length - worldChanges.length - carriedChanges.length;
  let unlinked = 0;
  for (const sc of game.scenes) for (const t of sc.tokens) if (!t.actorLink && t.delta?.items?.size) unlinked++;
  if (unlinked) notes.push(`${unlinked} unlinked token(s) on scenes keep their own item list and are not updated by this macro.`);
  if (!worldItems.length) notes.push(`No power items of type "${CFG.itemType}" were found in this world. Run the Tier 1 powers macro first.`);

  if (CFG.mode === "apply") {
    const ups = worldChanges.map(it => {
      const u = { _id: it.id, img: want(it) };
      if (it.getFlag("world", CFG.flag) === undefined) u[`flags.world.${CFG.flag}`] = it.img;
      return u;
    });
    for (let i = 0; i < ups.length; i += CFG.chunk) await Item.updateDocuments(ups.slice(i, i + CFG.chunk));
    const byActor = new Map();
    for (const { actor, item } of carriedChanges) {
      const u = { _id: item.id, img: want(item) };
      if (item.getFlag("world", CFG.flag) === undefined) u[`flags.world.${CFG.flag}`] = item.img;
      if (!byActor.has(actor)) byActor.set(actor, []);
      byActor.get(actor).push(u);
    }
    for (const [actor, list] of byActor) await actor.updateEmbeddedDocuments("Item", list);
    ui.notifications.info(`Power icons: updated ${ups.length} world item(s) and ${carriedChanges.length} carried cop${carriedChanges.length === 1 ? "y" : "ies"}.`);
  }

  /* ---- report ------------------------------------------------------------- */
  log({ mode: CFG.mode, worldItems: worldItems.length, carried: carried.length, worldChanges: worldChanges.length, carriedChanges: carriedChanges.length, noIcon, noItem, notes });
  const verb = CFG.mode === "apply" ? "Updated" : "Would update";
  const sample = worldChanges.slice(0, 12).map(it => `<li>${esc(it.name)} <span style="opacity:.6">(${esc(discOf(it) || "astrokinesis")}) to ${esc(known(it).file)}</span></li>`).join("");
  const who = [...new Set(carriedChanges.map(c => c.actor.name))];
  const content = `<div style="max-height:60vh;overflow:auto">
    <p><b>${verb} ${worldChanges.length}</b> of ${worldItems.length} power item(s) in the world. ${sameCount} already set.</p>
    <p><b>${verb} ${carriedChanges.length}</b> cop${carriedChanges.length === 1 ? "y" : "ies"} carried by ${who.length} character(s)${who.length ? `: ${who.slice(0, 10).map(esc).join(", ")}${who.length > 10 ? " ..." : ""}` : ""}.</p>
    ${sample ? `<ul>${sample}${worldChanges.length > 12 ? "<li>...</li>" : ""}</ul>` : ""}
    ${noIcon.length ? `<p><b>No icon yet for ${noIcon.length} power(s)</b> in this world (left alone): ${noIcon.map(esc).join(", ")}.</p>` : ""}
    ${noItem.length ? `<p>${noItem.length} icon(s) have no matching power in this world: ${noItem.map(esc).join(", ")}.</p>` : ""}
    ${notes.length ? `<h3>Notes</h3><ul>${notes.map(n => `<li>${esc(n)}</li>`).join("")}</ul>` : ""}
    ${CFG.mode === "dry" ? "<p>Nothing was changed. Set mode to \"apply\" to make these changes.</p>" : ""}</div>`;
  const DialogV2 = foundry?.applications?.api?.DialogV2;
  try {
    if (DialogV2) await DialogV2.prompt({ window: { title: "Power icons" }, content, ok: { label: "Close" } });
    else new Dialog({ title: "Power icons", content, buttons: { ok: { label: "Close" } } }).render(true);
  } catch (e) { log("summary window failed", e); }
})();
